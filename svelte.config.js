import fs from 'node:fs';
import adapterNode from '@sveltejs/adapter-node';
import adapterStatic from '@sveltejs/adapter-static';
import { vitePreprocess } from '@sveltejs/vite-plugin-svelte';

// DEMO=1 builds the static demo (GitHub Pages): no server, the API runs in the browser on
// SQLite/WASM. BASE_PATH serves the app under a sub-path (the demo defaults to /self-guitar).
const DEMO = process.env.DEMO === '1';
const BASE = (process.env.BASE_PATH ?? (DEMO ? '/self-guitar' : '')).replace(/\/$/, '');

/** Every page of the demo is a real file, so deep links work on a static host. */
function demoEntries() {
	const { songs, learn } = JSON.parse(fs.readFileSync('generated/content.json', 'utf8'));
	return [
		'*',
		...songs.map((s) => `/play/${s.id}`),
		...learn.lessons.map((l) => `/learn/${l.id}`),
		...learn.exercises.map((e) => `/practice/exercise/${e.id}`)
	];
}

/** @type {import('@sveltejs/kit').Config} */
const config = {
	preprocess: vitePreprocess(),
	kit: {
		adapter: DEMO
			? adapterStatic({ pages: 'build-demo', assets: 'build-demo', fallback: '404.html' })
			: adapterNode(),
		// Absolute asset URLs: the prerendered "/" shell is served offline for every route.
		paths: { base: BASE, relative: false },
		// The service worker is generated by @vite-pwa/sveltekit.
		serviceWorker: { register: false },
		...(DEMO ? { prerender: { entries: demoEntries() } } : {})
	}
};

export default config;
